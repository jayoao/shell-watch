_COMPILED = [(code, name, re.compile(pat), duty) for code, name, pat, duty in HAZARDS]


def classify(violation: str) -> list[str]:
    """回傳危害代碼清單。一筆可能同時屬於多類（例如墜落＋承攬管理）。"""
    t = violation or ""
    hits = [code for code, _n, rx, _d in _COMPILED if rx.search(t)]
    # 收容類別只有在什麼都沒中的時候才留
    if len(hits) > 1 and "general" in hits:
        hits = [h for h in hits if h != "general"]
    # 墜落與跌倒互斥。「高度二公尺以上之屋頂、階梯、坡道」講的是墜落，
    # 但含有「階梯」「坡道」；歸到墜落之後就不要再算成跌倒。
    if "fall" in hits and "trip" in hits:
        hits = [h for h in hits if h != "trip"]
    return hits


def is_fatal(violation: str) -> bool:
    """這一筆是不是涉及死亡災害。

    ⚠ 這是**公告文字裡提到**死亡災害，不等於這家公司害死了人 ——
      有些是「未於八小時內通報死亡災害」，罰的是通報義務不是災害本身。
      呈現時措辭要精確：「本筆公告涉及死亡災害」，不是「造成死亡」。
    """
    return bool(FATAL.search(violation or ""))


def main() -> int:
    use_utf8_stdout()
    if not RECORDS.exists():
        print(f"找不到 {RECORDS}", file=sys.stderr)
        return 1
    rows = [r for r in csv.DictReader(RECORDS.open(encoding="utf-8-sig"))
            if r.get("law") == "職業安全衛生法"]
    total = len(rows)
    counts = Counter()
    multi = fatal = 0
    unmatched = []
    for r in rows:
        v = r.get("violation", "")
        fatal += is_fatal(v)
        hits = classify(v)
        if not hits:
            unmatched.append(v)
            continue
        multi += len(hits) > 1
        for h in hits:
            counts[h] += 1

    matched = total - len(unmatched)
    print(f"職安法 {total:,} 筆")
    print(f"歸類成功 {matched:,}（{100 * matched / total:.1f}%）"
          f"　其中 {multi:,} 筆同時屬於多類\n")

    names = {c: n for c, n, _, _ in HAZARDS}
    print(f"  {'危害型態':<16}{'筆數':>9}{'佔比':>8}")
    for code, n in counts.most_common():
        print(f"  {names[code]:<16}{n:>9,}{100 * n / total:>7.1f}%")

    print(f"\n  ⚠ 其中 {fatal:,} 筆（{100 * fatal / total:.1f}%）的公告文字"
          f"提到**死亡災害**")
    print("     （包含未依規定通報死亡災害者 —— 罰的是通報義務，"
          "不是災害本身，措辭不能混）")

    if unmatched:
        print(f"\n  歸不進去的 {len(unmatched):,} 筆，最常見的 8 種：")
        for v, n in Counter(unmatched).most_common(8):
            print(f"    {n:>5,}  {v[:58]}")

    print("""
⚠ 「未指明的設備措施不足」是收容類別 —— 它是全國最常見的描述，
   但只寫「未符合規定」，沒說是哪一種危害。
   呈現時要老實說「本筆公告未指明危害型態」，不要硬歸到某一類。""")
    return 0


